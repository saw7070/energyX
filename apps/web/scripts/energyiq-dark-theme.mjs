#!/usr/bin/env node
/**
 * Generates the dark-theme block at the end of each EnergyIQ CSS module.
 *
 * Light styles stay the source of truth. For every rule that sets a colour, this writes a matching rule scoped to
 * `html[data-energyiq-theme="dark"]` with the colour moved to the dark palette: light tinted surfaces become dark
 * tinted surfaces, dark text becomes light text, light borders become dark borders. Hue is kept, so brand greens,
 * warning ambers and error reds still read as themselves. Saturated fills such as primary buttons are kept.
 *
 * Run after editing any listed module:  node scripts/energyiq-dark-theme.mjs
 * Check without writing (CI):           node scripts/energyiq-dark-theme.mjs --check
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../src/app/energyiq/_components");
export const MODULES = [
  "action-ai-estimate", "confirm-dialog", "data-availability", "energyiq-account-menu", "energyiq-top-bar", "holiday-calendar", "key-points", "project-actions",
  "meter-health-notice", "new-site", "project-configuration-view", "project-switcher", "report-action-panel", "report-workbench", "site-devices",
].map(name => join(ROOT, `${name}.module.css`));
const START = "/* energyiq-dark-theme:start — generated by scripts/energyiq-dark-theme.mjs; do not edit by hand */";
const END = "/* energyiq-dark-theme:end */";
// :where() adds no specificity, so each dark rule ranks exactly like its light rule and the dark block mirrors the light cascade.
const SCOPE = ':global(:where(html[data-energyiq-theme="dark"]))';

// ---------- colour maths (sRGB <-> OKLCH) ----------
const toLinear = c => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const fromLinear = c => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
function rgbToOklch([r, g, b]) {
  const [lr, lg, lb] = [r, g, b].map(v => toLinear(v / 255));
  const l = Math.cbrt(0.4122214708 * lr + 0.5363325363 * lg + 0.0514459929 * lb);
  const m = Math.cbrt(0.2119034982 * lr + 0.6806995451 * lg + 0.1073969566 * lb);
  const s = Math.cbrt(0.0883024619 * lr + 0.2817188376 * lg + 0.6299787005 * lb);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
  const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  return [L, Math.hypot(A, B), Math.atan2(B, A)];
}
function oklchToRgb([L, C, h]) {
  for (let c = C; c >= 0; c -= 0.005) {
    const A = c * Math.cos(h), B = c * Math.sin(h);
    const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
    const m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
    const s = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
    const rgb = [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s].map(fromLinear);
    if (rgb.every(v => v >= -0.001 && v <= 1.001)) return rgb.map(v => Math.round(Math.min(1, Math.max(0, v)) * 255));
  }
  const grey = Math.round(Math.min(1, Math.max(0, fromLinear(L ** 3))) * 255);
  return [grey, grey, grey];
}

// ---------- parsing colours ----------
const COLOUR = /#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b|rgba?\([^)]*\)|\bwhite\b|\bblack\b/g;
function parse(token) {
  if (token === "white") return { rgb: [255, 255, 255], a: 1 };
  if (token === "black") return { rgb: [0, 0, 0], a: 1 };
  if (token.startsWith("#")) {
    let hex = token.slice(1);
    if (hex.length <= 4) hex = [...hex].map(ch => ch + ch).join("");
    const n = [0, 2, 4, 6].map(i => parseInt(hex.slice(i, i + 2) || "ff", 16));
    return { rgb: n.slice(0, 3), a: hex.length === 8 ? n[3] / 255 : 1 };
  }
  const parts = token.slice(token.indexOf("(") + 1, -1).split(/[\s,/]+/).filter(Boolean);
  const rgb = parts.slice(0, 3).map(v => (v.endsWith("%") ? parseFloat(v) * 2.55 : parseFloat(v)));
  const alpha = parts[3] === undefined ? 1 : parts[3].endsWith("%") ? parseFloat(parts[3]) / 100 : parseFloat(parts[3]);
  return { rgb, a: alpha };
}
const format = ({ rgb, a }) => {
  const hex = rgb.map(v => v.toString(16).padStart(2, "0")).join("");
  return a >= 0.999 ? `#${hex}` : `#${hex}${Math.round(a * 255).toString(16).padStart(2, "0")}`;
};

/** Move one colour to the dark palette according to what it paints. */
export function darkColour(token, role) {
  const { rgb, a } = parse(token);
  let [L, C, h] = rgbToOklch(rgb);
  if (role === "text") {
    if (L >= 0.62) return token;
    L = 0.97 - L * 0.45; C = Math.min(C, 0.12);
  } else if (role === "background") {
    if (L > 0.72) { L = 0.215 + (1 - L) * 0.55; C = Math.min(C, 0.045); }
    else if (L < 0.3 && C < 0.03) L = 0.3;
    else return token;
  } else if (role === "border") {
    if (L <= 0.7) return token;
    L = 0.3 + (1 - L) * 0.35; C = Math.min(C, 0.05);
  } else if (role === "shadow") {
    if (L <= 0.7) return format({ rgb, a: Math.min(1, a * 1.6) });
    L = 0.12; C = Math.min(C, 0.02);
  }
  return format({ rgb: oklchToRgb([L, C, h]), a });
}

const ROLES = [
  [/^(color|caret-color|-webkit-text-fill-color|fill)$/, "text"],
  [/^(background|background-color|background-image)$/, "background"],
  [/^(border(-[a-z-]+)?|outline(-color)?|text-decoration(-color)?|column-rule(-color)?|stroke)$/, "border"],
  [/^(box-shadow|text-shadow)$/, "shadow"],
];
const roleOf = property => ROLES.find(([pattern]) => pattern.test(property))?.[1];

// ---------- CSS walking ----------
function splitTopLevel(text, separator) {
  const out = []; let depth = 0, start = 0;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (ch === "(") depth += 1; else if (ch === ")") depth -= 1;
    else if (ch === separator && depth === 0) { out.push(text.slice(start, i)); start = i + 1; }
  }
  out.push(text.slice(start));
  return out;
}
function blocks(css) {
  const items = []; let i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i);
    if (open === -1) break;
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === "{") depth += 1; else if (css[j] === "}") depth -= 1; j += 1; }
    items.push({ head: css.slice(i, open).trim(), body: css.slice(open + 1, j - 1) });
    i = j;
  }
  return items;
}
function darkRules(css) {
  const out = [];
  for (const { head, body } of blocks(css)) {
    if (head.startsWith("@media") || head.startsWith("@supports") || head.startsWith("@container")) {
      const inner = darkRules(body);
      if (inner.length) out.push(`${head} {\n${inner.map(rule => `  ${rule}`).join("\n")}\n}`);
      continue;
    }
    if (head.startsWith("@")) continue;
    const declarations = splitTopLevel(body, ";").flatMap(part => {
      const colon = part.indexOf(":");
      if (colon === -1) return [];
      const property = part.slice(0, colon).trim().toLowerCase(), value = part.slice(colon + 1).trim();
      const role = roleOf(property);
      if (!role) return [];
      // Every colour declaration is repeated, even ones without a literal colour (transparent, var(...)), so the dark
      // block keeps the light cascade: a later light rule that resets a colour still beats an earlier rule's dark colour.
      return [`${property}:${value.replace(COLOUR, token => darkColour(token, role))}`];
    });
    if (!declarations.length) continue;
    const selector = splitTopLevel(head, ",").map(part => `${SCOPE} ${part.trim()}`).join(", ");
    out.push(`${selector} { ${declarations.join("; ")}; }`);
  }
  return out;
}
export function withDarkTheme(source) {
  const base = source.includes(START) ? source.slice(0, source.indexOf(START)).trimEnd() : source.trimEnd();
  const light = base.replace(/\/\*[\s\S]*?\*\//g, "");
  const rules = darkRules(light);
  return `${base}\n\n${START}\n${rules.join("\n")}\n${END}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const file of MODULES) {
    const source = readFileSync(file, "utf8"), next = withDarkTheme(source);
    if (next === source) continue;
    if (check) { stale += 1; console.error(`Dark theme out of date: ${file}`); } else { writeFileSync(file, next); console.log(`Updated ${file}`); }
  }
  if (check && stale) process.exit(1);
}
