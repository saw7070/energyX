/** Dates in the reader's language; English keeps the Singapore style used elsewhere ("1 Sept 2026"). */
export const importDateLocale = (locale: EnergyIqLocale): string =>
  locale === "zh-Hans" ? "zh-CN" : locale === "ms" ? "ms-MY" : "en-SG";
