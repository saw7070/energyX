import { createElement, Fragment, type ReactNode } from "react";
import { defineMessages, intlLocale, translatorFor, type EnergyIqLocale } from "./energyiq-messages";

/**
 * Locale for dates the reader sees. English keeps each screen's existing English format (some screens use "en-GB"
 * for a 24-hour clock); other languages follow Singapore conventions.
 */
export const dateLocale = (locale: EnergyIqLocale, english = "en-SG") => locale === "en" ? english : intlLocale(locale);

/** Fills `{name}` placeholders with elements (a link, bold text) so a translated sentence keeps its own word order. */
export function fillTemplate(text: string, nodes: Record<string, ReactNode>): ReactNode[] {
  return text.split(/\{(\w+)\}/).map((part, index) => createElement(Fragment, { key: index }, index % 2 ? nodes[part] ?? `{${part}}` : part));
}

