/**
 * How long a report covers, in the words a reader would use: a weekly report reads "1 week", a monthly one
 * "1 month". A report is only called a month when it runs from the first to the last day of calendar months.
 */
export function coverageLabel(from: string, toExclusive: string, locale: EnergyIqLocale = "en"): string {
  const t = translatorFor(libraryMessages, locale);
  const start = new Date(`${from}T00:00:00Z`), end = new Date(`${toExclusive}T00:00:00Z`);
  const days = Math.round((end.getTime() - start.getTime()) / 86400000);
  if (!Number.isFinite(days) || days < 1) return "";
  const wholeMonths = start.getUTCDate() === 1 && end.getUTCDate() === 1
    ? (end.getUTCFullYear() - start.getUTCFullYear()) * 12 + end.getUTCMonth() - start.getUTCMonth()
    : 0;
  if (wholeMonths === 1) return t("coverMonth");
  if (wholeMonths > 1) return t("coverMonths", { count: wholeMonths });
  if (days === 1) return t("coverDay");
  if (days === 7) return t("coverWeek");
  if (days % 7 === 0 && days <= 28) return t("coverWeeks", { count: days / 7 });
  return t("coverDays", { count: days });
}
