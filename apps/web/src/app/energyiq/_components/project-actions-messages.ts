/**
 * A label for a value that comes from the API, e.g. `labelFor(t, book, `status.${value}`, value)`.
 * Unknown values are shown as they are rather than hidden.
 */
export function labelFor<K extends string>(t: Translate<K>, book: Translations<K>, key: string, fallback: string): string {
  return Object.hasOwn(book.en, key) ? t(key as K) : fallback;
}

/**
 * Splits translated text around a `{name}` placeholder so a React element (a <time>, a <strong>) can sit inside the
 * sentence wherever the language puts it: `const [before, after] = around(t("recorded"), "time")`.
 */
export function around(text: string, name: string): [string, string] {
  const token = `{${name}}`, at = text.indexOf(token);
  return at < 0 ? [text, ""] : [text.slice(0, at), text.slice(at + token.length)];
}

