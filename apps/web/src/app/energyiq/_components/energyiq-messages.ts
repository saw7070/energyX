/**
 * EnergyX's own wording, and the language machinery every area's wording is built on. The machinery
 * (`EnergyIqLocale`, `defineMessages`, `translatorFor`, `intlLocale`) lives in @datafoundry/site-report so the server
 * can word a saved report exactly as the page does; it is re-exported here unchanged, so pages keep importing it from
 * this file.
 */
