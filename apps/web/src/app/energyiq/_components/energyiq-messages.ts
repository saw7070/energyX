export const LANGUAGE_STORAGE_KEY = "energyiq-language";

/** Each language is listed in its own script so a reader can find theirs without reading the current one. */
export const LOCALES: Array<{ id: EnergyIqLocale; name: string; short: string }> = [
  { id: "en", name: "English", short: "EN" },
  { id: "zh-Hans", name: "简体中文", short: "中文" },
  { id: "ms", name: "Bahasa Melayu", short: "BM" },
];
export const isLocale = (value: unknown): value is EnergyIqLocale => LOCALES.some(locale => locale.id === value);

/**
 * Runs in the page before first paint (see the EnergyX layout) so screen readers and fonts pick up the saved
 * language straight away. The text itself switches once the page's scripts load.
 */
export const LANGUAGE_BOOT_SCRIPT = `try{var l=localStorage.getItem("${LANGUAGE_STORAGE_KEY}");if(${JSON.stringify(LOCALES.map(locale => locale.id))}.indexOf(l)>=0)document.documentElement.lang=l;}catch(e){}`;

