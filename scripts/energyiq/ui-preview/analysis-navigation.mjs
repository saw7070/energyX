import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const base='http://127.0.0.1:3185/energyiq/';
await page.goto(base+'reports?projectId=ui-demo&sessionId=demo-chat',{waitUntil:'networkidle'});
const input=page.getByRole('textbox',{name:'Report instructions',exact:true});
await input.fill('Keep this unsent question');
await page.getByRole('button',{name:'Last month',exact:true}).click();
await page.getByRole('button').filter({hasText:'Weekly energy review · Demo'}).click();
await page.getByRole('complementary',{name:'File preview'}).waitFor();
assert.equal(await input.inputValue(),'Keep this unsent question');
assert.match(page.url(),/sessionId=demo-chat/);
assert.equal(await page.getByText('Using the selected report as context').count(),0);
await page.getByRole('complementary',{name:'File preview'}).getByRole('button',{name:'Discuss this report',exact:true}).click();
await page.getByText('Using the selected report as context').waitFor();
assert.equal(await input.inputValue(),'Keep this unsent question');
await page.screenshot({path:'artifacts/ui-preview/analysis-report-context.png'});
await page.goto(base+'library?projectId=ui-demo',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Automatic reports',exact:true}).click();
let dialog=page.getByRole('dialog',{name:'Automatic reports'});
await dialog.getByRole('button',{name:'Save schedule'}).waitFor();
assert.equal(await dialog.getByText('Building and operating context').count(),0);
await page.screenshot({path:'artifacts/ui-preview/automatic-reports.png'});
await page.keyboard.press('Escape');
await page.goto(base+'project-configuration?projectId=ui-demo',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Project background & materials',exact:true}).click();
dialog=page.getByRole('dialog',{name:'Project background & materials'});
await dialog.getByRole('button',{name:'Save project background'}).waitFor();
assert.equal(await dialog.getByRole('combobox',{name:'Report frequency'}).count(),0);
await page.screenshot({path:'artifacts/ui-preview/project-background.png'});
assert.deepEqual(errors,[]);
writeFileSync('artifacts/ui-preview/analysis-navigation.json',JSON.stringify({checks:['one-click range','preview preserves draft and session','explicit report context','schedule settings','project settings','no page errors'],errors},null,2));
await browser.close();
